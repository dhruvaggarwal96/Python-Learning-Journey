-- Hard Questions (21–25)
-- =====================================================

--  Find cities where total revenue is greater than 10, 000 
SELECT city ,SUM(quantity * price ) AS total_revenue 
FROM sales 
GROUP BY city 
HAVING total_revenue > 10000;

-- Find the second highest priced product.
SELECT product , price 
FROM sales 
ORDER BY price DESC
LIMIT 1 OFFSET 1;

-- Find categories contributing more than 30% of total revenue. 
SELECT category , SUM(quantity * price ) AS total_revenue 
FROM sales 
GROUP BY category
HAVING SUM(quantity * price ) > ( 
									SELECT SUM(quantity * price) * 0.30 
                                    FROM sales 
								) ;
                                
-- Find the city with the highest average order value.
SELECT city,
       AVG(quantity * price) AS avg_order_value
FROM sales
GROUP BY city
ORDER BY avg_order_value DESC
LIMIT 1;


-- Find the category whose total revenue is above the overall average category revenue.
SELECT category , SUM(quantity * price) AS total_revenue 
FROM sales 
GROUP BY category 
HAVING SUM(quantity * price) > 
	(
    SELECT AVG(category_revenue) AS Avg_category_revenue
	FROM 
		( SELECT SUM(quantity * price) AS category_revenue 
		FROM sales 
		GROUP BY category ) AS category_revenue_table 
	) ; 
