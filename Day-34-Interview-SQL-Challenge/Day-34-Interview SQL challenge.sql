-- Easy Questions (1–10)
-- =====================================================

-- Display all columns from the sales table.
SELECT * FROM sales ;

-- Show only customer_name and city.
SELECT customer_name , city FROM sales ;

-- Find orders where city = 'Delhi'.
SELECT * FROM sales 
WHERE city = "Delhi";

-- Find products with price > 500.
SELECT product , price FROM sales 
WHERE price > 500;

-- Find orders where quantity >= 5 
SELECT * FROM sales 
WHERE quantity >= 5;

-- Show unique categories.
SELECT DISTINCT category FROM sales ;

-- Sort products by price in ascending order.
SELECT product , price 
FROM sales 
ORDER BY price ASC;

-- Sort products by price in descending order.
SELECT product , price 
FROM sales 
ORDER BY price DESC;

-- Display the first 5 rows. 
SELECT * FROM sales 
LIMIT 5;

-- Find orders placed after '2024-01-01'. 
SELECT * FROM sales 
WHERE order_date > '2024-01-01';

-- ==========================================
-- Medium Questions
-- ==========================================

-- Calculate total revenue for each row (quantity * price). 
SELECT quantity * price AS Total_revenue FROM sales;

-- Find total quantity sold per category. 
SELECT category , SUM(quantity ) AS Total_quantity FROM sales 
GROUP BY category;

-- Find average price per category.
SELECT category , AVG(price) FROM sales 
GROUP BY category ;

-- Count orders in each city.
SELECT city , COUNT(order_id) AS Number_of_orders FROM sales  
GROUP BY city;

-- Find total revenue generated by each city.
SELECT city , SUM(quantity * price ) AS Total_revenue 
FROM sales 
GROUP BY city ;

-- Display cities having more than 3 orders.
SELECT city , COUNT(order_id) AS Orders 
FROM sales 
GROUP BY city 
HAVING Orders > 3;

-- Find categories with average price greater than 1000.
SELECT category , AVG(price) AS Avg_price 
FROM sales 
GROUP BY category 
HAVING Avg_price > 1000;

-- Find the top 3 most expensive products.
SELECT product , price 
FROM sales 
ORDER BY price DESC 
LIMIT 3;

-- Find the total number of unique customers.
SELECT COUNT(DISTINCT customer_name) AS total_number_of_unique_customer
FROM sales ;

-- Find the category with the highest total quantity sold.
SELECT category , SUM(quantity ) AS total_quantity_sold
FROM sales 
GROUP BY category
ORDER BY SUM(quantity) DESC 
LIMIT 1;

